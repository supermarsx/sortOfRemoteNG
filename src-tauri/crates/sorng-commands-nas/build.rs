fn main() {
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows")
        && std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc")
    {
        // Tauri's mock runtime still links Common Controls v6 functions such as
        // TaskDialogIndirect. Unit-test executables do not pass through the app's
        // tauri-build manifest, so they need this activation context themselves.
        // Without it Windows exits with STATUS_ENTRYPOINT_NOT_FOUND before tests.
        println!("cargo:rustc-link-arg=/MANIFEST:EMBED");
        println!(
            "cargo:rustc-link-arg=/MANIFESTDEPENDENCY:type='win32' name='Microsoft.Windows.Common-Controls' version='6.0.0.0' processorArchitecture='*' publicKeyToken='6595b64144ccf1df' language='*'"
        );
    }
}
