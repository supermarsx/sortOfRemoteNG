/**
 * Built-in Arista EOS scripts for the Bulk SSH Commander.
 *
 * Conventions used throughout this set:
 *
 * - **Three execution contexts.** Most read-only scripts stop at `enable` and
 *   never enter configuration mode. Config scripts run `configure terminal`,
 *   apply the change, `end`, then `write memory` to persist it. One script
 *   (the transceiver flash-flag method) drops out of the EOS CLI into the
 *   switch's underlying Linux `bash` shell; it is the only one that does.
 *
 * - **Every script verifies itself.** Each one ends in the `show` command that
 *   proves the change landed, so an operator can tell success from silence.
 *
 * - **Single vs. range verification.** Scripts targeting one object verify that
 *   object (`show vlan 101`, `show interfaces Ethernet29 status`); scripts
 *   targeting a range verify switch-wide (`show interfaces status`), because
 *   per-interface output for a range is unwieldy and the whole-switch view is
 *   what you actually want after a bulk change. The same summary/detail and
 *   one/all pairing recurs for VLANs, MAC table, counters, LLDP and
 *   environment sensors.
 *
 * - **Ready-to-run plus parameterised.** Where a script has a concrete target,
 *   it ships twice: once with real working values, and once with `<TOKEN>`
 *   placeholders for other targets. Load the `(Custom)` variant into the
 *   command box, replace the tokens, then run. Placeholders are documented in
 *   each description rather than as comment lines, so the script stays valid
 *   the moment the tokens are replaced.
 *
 * - **Risk.** `isDestructiveBulkScript` derives the confirmation prompt from
 *   content. Read-only scripts must stay free of mutating commands so they do
 *   not train the operator to click through confirmations; anything that
 *   changes configuration, clears runtime state, downs a port or reboots is
 *   flagged and prompts before running.
 */
