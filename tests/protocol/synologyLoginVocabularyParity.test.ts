/* Minimal ES5 source scanner: strings, comments, regex literals, brackets. */
function regexAllowed(text: string, index: number) {
  let cursor = index - 1;
  while (cursor >= 0 && /\s/.test(text[cursor])) cursor--;
  if (cursor < 0 || "(,=:[!&|?{};+-*%<>~^".includes(text[cursor])) return true;
  return /\b(?:return|typeof|case|in|of|void|delete)$/.test(
    text.slice(Math.max(0, cursor - 7), cursor + 1),
  );
}
/** Index after a string, comment or regex literal starting at `index`, else `index`. */
function skipLiteral(text: string, index: number): number {
  const char = text[index];
  if (char === '"' || char === "'" || char === "`") {
    for (let cursor = index + 1; cursor < text.length; cursor++) {
      if (text[cursor] === "\\") cursor++;
      else if (text[cursor] === char) return cursor + 1;
    }
    return text.length;
  }
  if (char !== "/") return index;
  if (text[index + 1] === "/") {
    const end = text.indexOf("\n", index);
    return end < 0 ? text.length : end;
  }
  if (text[index + 1] === "*") {
    const end = text.indexOf("*/", index + 2);
    return end < 0 ? text.length : end + 2;
  }
  if (!regexAllowed(text, index)) return index;
  let inClass = false;
  for (let cursor = index + 1; cursor < text.length; cursor++) {
    const next = text[cursor];
    if (next === "\\") cursor++;
    else if (next === "\n") return index;
    else if (next === "[") inClass = true;
    else if (next === "]") inClass = false;
    else if (next === "/" && !inClass) return cursor + 1;
  }
  return index;
}
const PAIRS: Record<string, string> = { "(": ")", "[": "]", "{": "}" };
/** Index of the bracket that closes the one at `open`. */
function closing(text: string, open: number): number {
  const stack = [PAIRS[text[open]]];
  for (let cursor = open + 1; cursor < text.length;) {
    const next = skipLiteral(text, cursor);
    if (next !== cursor) {
      cursor = next;
      continue;
    }
    const char = text[cursor];
    if (PAIRS[char]) stack.push(PAIRS[char]);
    else if (char === stack[stack.length - 1]) {
      stack.pop();
      if (!stack.length) return cursor;
    }
    cursor++;
  }
  return -1;
}
/** Splits at top-level commas; stops at an unbalanced closer or a top-level `;`. */
function splitTopLevel(text: string, stopAtSemicolon = false): string[] {
  const parts: string[] = [];
  let depth = 0,
    start = 0;
  for (let cursor = 0; cursor < text.length;) {
    const next = skipLiteral(text, cursor);
    if (next !== cursor) {
      cursor = next;
      continue;
    }
    const char = text[cursor];
    if (PAIRS[char]) depth++;
    else if (")]}".includes(char)) {
      if (depth === 0) return [...parts, text.slice(start, cursor)];
      depth--;
    } else if (depth === 0 && char === ",") {
      parts.push(text.slice(start, cursor));
      start = cursor + 1;
    } else if (depth === 0 && char === ";" && stopAtSemicolon)
      return [...parts, text.slice(start, cursor)];
    cursor++;
  }
  return [...parts, text.slice(start)];
}
const QUOTED = String.raw`(?:"(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*')`;
const literals = (text: string) =>
  [...text.matchAll(new RegExp(QUOTED, "g"))].map((match) =>
    match[0].slice(1, -1),
  );
const NOT_CALLS = new Set([
  "if",
  "for",
  "while",
  "switch",
  "catch",
  "function",
  "return",
  "typeof",
  "void",
  "in",
  "of",
]);
/** Replaces every call's argument list with `()`, keeping grouping parentheses. */
function stripCallArguments(text: string): string {
  let result = "";
  for (let cursor = 0; cursor < text.length;) {
    const next = skipLiteral(text, cursor);
    if (next !== cursor) {
      result += text.slice(cursor, next);
      cursor = next;
      continue;
    }
    if (text[cursor] === "(") {
      const before = result.replace(/\s+$/, "");
      const word = /[A-Za-z_$][\w$]*$/.exec(before)?.[0];
      const close = closing(text, cursor);
      if (
        close > cursor &&
        ((word && !NOT_CALLS.has(word)) || /[)\]]$/.test(before))
      ) {
        result += "()";
        cursor = close + 1;
        continue;
      }
    }
    result += text[cursor++];
  }
  return result;
}
// Call arguments and literals compared against are not the value an
// expression produces, so they are removed before collecting values.
const valueExpression = (text: string) =>
  stripCallArguments(text)
    .replace(
      new RegExp(String.raw`[\w$.\])]+\s*(?:===|!==|==|!=)\s*${QUOTED}`, "g"),
      " ",
    )
    .replace(
      new RegExp(String.raw`${QUOTED}\s*(?:===|!==|==|!=)\s*[\w$.]+`, "g"),
      " ",
    );
const KEYWORDS = new Set([
  "true",
  "false",
  "null",
  "undefined",
  "this",
  "typeof",
  "void",
  "new",
  "in",
  "instanceof",
  "return",
  "var",
  "function",
  "delete",
]);
interface Reference {
  name: string;
  member: boolean;
  call: boolean;
}
/** Plain identifiers, the last property of member chains, and called names. */
function references(text: string): Reference[] {
  const code = text.replace(new RegExp(QUOTED, "g"), " ");
  return [
    ...code.matchAll(
      /(?<![\w$.])([A-Za-z_$][\w$]*)((?:\s*\.\s*[A-Za-z_$][\w$]*)*)(\s*\()?/g,
    ),
  ].flatMap((match) => {
    const members = match[2]
      .split(".")
      .map((part) => part.trim())
      .filter(Boolean);
    const name = members.length ? members[members.length - 1] : match[1];
    if (!members.length && KEYWORDS.has(name)) return [];
    return [{ name, member: members.length > 0, call: !!match[3] }];
  });
}

interface Definition {
  name: string;
  params: string[];
  open: number;
  close: number;
}
function definitions(text: string): Definition[] {
  return [
    ...text.matchAll(/function\s+([A-Za-z_$][\w$]*)\s*\(([^)]*)\)\s*\{/g),
  ].map((match) => {
    const open = match.index! + match[0].length - 1;
    return {
      name: match[1],
      params: match[2]
        .split(",")
        .map((param) => param.trim())
        .filter(Boolean),
      open,
      close: closing(text, open),
    };
  });
}
function calls(text: string, name: string) {
  const pattern = new RegExp(String.raw`(?<![\w$.])${name}\s*\(`, "g");
  return [...text.matchAll(pattern)].flatMap((match) => {
    const before = text.slice(Math.max(0, match.index! - 12), match.index);
    if (/function\s+$/.test(before)) return [];
    const open = match.index! + match[0].length - 1;
    const close = closing(text, open);
    return close > open
      ? [
          {
            offset: match.index!,
            args: splitTopLevel(text.slice(open + 1, close)),
          },
        ]
      : [];
  });
}
interface Source {
  expression: string;
  offset: number;
}
/** Right-hand sides matched by `pattern` within [from, to). */
function rightHandSides(
  text: string,
  pattern: RegExp,
  from = 0,
  to = text.length,
  stopAtSemicolon = true,
): Source[] {
  return [...text.slice(from, to).matchAll(pattern)].map((match) => {
    const offset = from + match.index! + match[0].length;
    return {
      expression: splitTopLevel(text.slice(offset), stopAtSemicolon)[0],
      offset,
    };
  });
}
const assignmentPattern = (name: string) =>
  new RegExp(String.raw`(?<![\w$.])${name}\s*=(?!=)`, "g");

type Kind = "phase" | "reason";
interface Slot {
  kind: Kind;
  suffixes: string[];
}
// Single-word values in the contract; other values must be snake or kebab case.
const SINGLE_WORD = {
  phase: CONTRACT.phases.filter((value) => !value.includes("_")),
  reason: CONTRACT.reasons.filter((value) => !value.includes("-")),
};
const SHAPE = {
  phase: /^[a-z]+(?:_[a-z]+)+$/,
  reason: /^[a-z]+(?:-[a-z]+)+$/,
};
/**
 * Status values flow into `publish(phase, reason)`, `reject(reason)` and
 * `failureReason = reason`. A function forwarding its own parameter into one
 * of those becomes a sink too. Values are then followed through local
 * assignments (nearest enclosing function first), object properties
 * (`found.missing`), function return values and generated `-suffix` names.
 */
function extractHelperVocabulary(text: string) {
  const defs = definitions(text);
  const chain = (offset: number) =>
    defs
      .filter((def) => def.open < offset && offset < def.close)
      .sort((left, right) => right.open - left.open);
  const sinks = new Map<string, Map<number, Slot>>([
    [
      "publish",
      new Map([
        [0, { kind: "phase", suffixes: [] }],
        [1, { kind: "reason", suffixes: [] }],
      ]),
    ],
    ["reject", new Map([[0, { kind: "reason", suffixes: [] }]])],
  ]);
  for (let round = 0, grew = true; grew && round < 8; round++) {
    grew = false;
    for (const [sink, slots] of [...sinks])
      for (const call of calls(text, sink))
        for (const [index, slot] of slots) {
          const expression = valueExpression(call.args[index] ?? "");
          const suffixes = literals(expression).filter((value) =>
            value.startsWith("-"),
          );
          for (const reference of references(expression)) {
            if (reference.member || reference.call) continue;
            const owner = chain(call.offset).find((def) =>
              def.params.includes(reference.name),
            );
            if (!owner || owner.name === sink) continue;
            const wrapper = sinks.get(owner.name) ?? new Map<number, Slot>();
            const param = owner.params.indexOf(reference.name);
            if (wrapper.has(param)) continue;
            wrapper.set(param, {
              kind: slot.kind,
              suffixes: suffixes.length ? suffixes : slot.suffixes,
            });
            sinks.set(owner.name, wrapper);
            grew = true;
          }
        }
  }
  const found = { phase: new Set<string>(), reason: new Set<string>() };
  const visited = new Set<string>();
  function resolve(
    expression: string,
    offset: number,
    kind: Kind,
    inherited: string[],
    depth = 0,
  ) {
    if (depth > 8) return;
    const value = valueExpression(expression);
    const values = literals(value);
    const own = values.filter((literal) => literal.startsWith("-"));
    const suffixes = own.length ? own : inherited;
    for (const literal of values) {
      if (literal.startsWith("-")) continue;
      for (const candidate of suffixes.length
        ? suffixes.map((suffix) => literal + suffix)
        : [literal])
        if (
          SHAPE[kind].test(candidate) ||
          SINGLE_WORD[kind].includes(candidate)
        )
          found[kind].add(candidate);
    }
    const enclosing = chain(offset);
    for (const reference of references(value)) {
      let sources: Source[] = [];
      let scope = "";
      if (reference.member) {
        if (reference.call) continue;
        sources = [
          ...rightHandSides(
            text,
            new RegExp(String.raw`[{,]\s*${reference.name}\s*:(?!:)`, "g"),
            0,
            text.length,
            false,
          ),
          ...rightHandSides(
            text,
            new RegExp(String.raw`\.\s*${reference.name}\s*=(?!=)`, "g"),
          ),
        ];
        scope = ".";
      } else if (reference.call) {
        sources = defs
          .filter((def) => def.name === reference.name)
          .flatMap((def) =>
            rightHandSides(text, /(?<![\w$.])return\b/g, def.open, def.close),
          );
        scope = "()";
      } else {
        if (enclosing.some((def) => def.params.includes(reference.name)))
          continue;
        const pattern = assignmentPattern(reference.name);
        for (const def of enclosing) {
          sources = rightHandSides(text, pattern, def.open, def.close);
          scope = String(def.open);
          if (sources.length) break;
        }
        if (!sources.length) {
          sources = rightHandSides(text, pattern);
          scope = "global";
        }
      }
      const key = `${kind}|${suffixes.join()}|${scope}|${reference.name}`;
      if (visited.has(key)) continue;
      visited.add(key);
      for (const source of sources)
        resolve(source.expression, source.offset, kind, suffixes, depth + 1);
    }
  }
  for (const source of rightHandSides(text, assignmentPattern("failureReason")))
    resolve(source.expression, source.offset, "reason", []);
  for (const [sink, slots] of sinks)
    for (const call of calls(text, sink))
      for (const [index, slot] of slots)
        resolve(call.args[index] ?? "", call.offset, slot.kind, slot.suffixes);
  return { phases: sorted(found.phase), reasons: sorted(found.reason) };
}
function bridgeList(name: string): string[] {
  const match = new RegExp(String.raw`var ${name} = \[([^\]]*)\]`).exec(bridge);
  if (!match) throw new Error(`bridge list ${name} not found`);
  return literals(match[1]);
}

