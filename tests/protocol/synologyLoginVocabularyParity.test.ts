type Published = { phase: string; reason: string; trace: unknown };
type HelperApi = {
  runWhenReady(nonce: string, helpers: unknown): Promise<unknown>;
  cancel(): void;
};
async function runHelperThroughBridge() {
  vi.useFakeTimers();
  history.replaceState(null, "", "/");
  const published: Published[] = [];
  const collect = (event: Event) => {
    const { phase, reason, trace } = (event as CustomEvent).detail;
    published.push({
      phase,
      reason,
      trace:
        trace === undefined ? undefined : JSON.parse(JSON.stringify(trace)),
    });
  };
  document.addEventListener("sorng_synology_login_progress", collect);
  installBridge();
  window.eval(helper);
  const api = (window as unknown as { __sorng_synology_login: HelperApi })
    .__sorng_synology_login;
  try {
    const running = api.runWhenReady("c".repeat(32), {
      fillField: vi.fn(),
      isVisible: () => true,
      report: vi.fn(),
    });
    await vi.advanceTimersByTimeAsync(1500);
    api.cancel();
    await vi.advanceTimersByTimeAsync(0);
    await running;
  } finally {
    document.removeEventListener("sorng_synology_login_progress", collect);
    window.removeEventListener("pagehide", api.cancel);
    window.removeEventListener("unload", api.cancel);
  }
  // The helper and the bridge both suppress a repeated phase:reason pair.
  return published.filter(
    (report, index) =>
      index === 0 ||
      `${report.phase}:${report.reason}` !==
        `${published[index - 1].phase}:${published[index - 1].reason}`,
  );
}
/** What the bridge must forward for a helper trace that meets the contract. */
function forwardedTrace(raw: Record<string, unknown>) {
  const expected: Record<string, unknown> = {};
  const steps = raw.steps as unknown[];
  if (steps.length) expected.steps = steps.slice(-8);
  const fingerprint = Object.fromEntries(
    Object.entries(raw.fingerprint as Record<string, unknown>).map(
      ([key, value]) => [
        key,
        typeof value === "number" ? Math.min(value, 9) : value,
      ],
    ),
  );
  if (Object.keys(fingerprint).length) expected.fingerprint = fingerprint;
  if (raw.handoff !== null) expected.handoff = raw.handoff;
  return Object.keys(expected).length ? expected : undefined;
}
const tracedHelper = /\btrace:\s*traceCopy\(\)|detail:\s*\{[^}]*\btrace\b/.test(
  helper,
);

