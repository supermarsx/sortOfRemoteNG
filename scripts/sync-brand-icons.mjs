#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import prettier from "prettier";

const REPOSITORY_ROOT = fileURLToPath(new URL("../", import.meta.url));
const BRAND_DIRECTORY = path.join(
  REPOSITORY_ROOT,
  "src",
  "utils",
  "icons",
  "brand",
);
const SLUGS_PATH = path.join(BRAND_DIRECTORY, "brandIconSlugs.ts");
const GENERATED_PATH = path.join(BRAND_DIRECTORY, "generatedBrandIcons.ts");
const SIMPLE_ICONS_ROOT = path.join(
  REPOSITORY_ROOT,
  "node_modules",
  "simple-icons",
);

function fail(message) {
  throw new Error(`Brand icon catalog: ${message}`);
}

/**
 * Extracts the hand-maintained slug list from `brandIconSlugs.ts`.
 *
 * The list is parsed rather than imported because this script runs on bare Node
 * with no TypeScript loader — the same reason `tests/tooling` parses the
 * generated Rust catalog with a regex.
 */
export function parseBrandIconSlugs(source) {
  const block =
    /export const BRAND_ICON_SLUGS = \[([\s\S]*?)\] as const;/u.exec(source);
  if (block === null) {
    fail(
      "brandIconSlugs.ts does not declare `BRAND_ICON_SLUGS` as a const array",
    );
  }

  const slugs = [...block[1].matchAll(/"([^"]*)"/gu)].map((match) => match[1]);
  if (slugs.length === 0) fail("brandIconSlugs.ts lists no slugs");

  const seen = new Set();
  for (const slug of slugs) {
    if (!/^[a-z0-9.+-]+$/u.test(slug))
      fail(`slug ${JSON.stringify(slug)} is malformed`);
    if (seen.has(slug)) fail(`slug ${slug} is listed more than once`);
    seen.add(slug);
  }
  return slugs;
}

/** `alpine-linux` -> `alpineLinux`; the identifier the generated module exports. */
export function brandIconIdentifier(slug) {
  const identifier = slug.replace(/[.+-]+([a-z0-9])?/gu, (_match, next) =>
    next === undefined ? "" : next.toUpperCase(),
  );
  if (!/^[a-z][a-zA-Z0-9]*$/u.test(identifier)) {
    fail(
      `slug ${slug} does not map to a usable identifier (got ${JSON.stringify(identifier)})`,
    );
  }
  return identifier;
}

/**
 * Reads one mark from the installed simple-icons.
 *
 * Fails loudly when a slug is absent so an upstream removal — how the Microsoft,
 * Amazon and Oracle families vanished — is a red build rather than a silently
 * missing icon, and when a mark is not a single path, because `createBrandIcon`
 * renders exactly one.
 */
export function readBrandIcon(
  slug,
  { iconsDirectory = path.join(SIMPLE_ICONS_ROOT, "icons") } = {},
) {
  const iconPath = path.join(iconsDirectory, `${slug}.svg`);
  if (!fs.existsSync(iconPath)) {
    fail(
      `slug ${slug} is not present in the installed simple-icons (looked for ${path.relative(REPOSITORY_ROOT, iconPath).replaceAll("\\", "/")}). ` +
        "Upstream may have removed it; drop it from brandIconSlugs.ts and hand-author the mark instead.",
    );
  }

  const svg = fs.readFileSync(iconPath, "utf8");
  const paths = [...svg.matchAll(/\sd="([^"]+)"/gu)].map((match) => match[1]);
  if (paths.length !== 1) {
    fail(
      `slug ${slug} has ${paths.length} paths; createBrandIcon renders exactly one`,
    );
  }

  const title = /<title>([^<]+)<\/title>/u.exec(svg);
  return {
    slug,
    identifier: brandIconIdentifier(slug),
    title: title === null ? slug : title[1],
    path: paths[0],
  };
}

export function collectBrandIcons(slugs, options = undefined) {
  const icons = slugs.map((slug) => readBrandIcon(slug, options));
  icons.sort((left, right) =>
    left.identifier.localeCompare(right.identifier, "en"),
  );
  return icons;
}

function tsString(value) {
  return `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

export function renderBrandIconModule(icons, version) {
  const declarations = icons
    .map(
      ({ identifier, title, path: pathData }) =>
        `export const ${identifier} = createBrandIcon(${tsString(title)}, ${tsString(pathData)});`,
    )
    .join("\n\n");
  // The record is keyed by *slug*, which is not always the exported identifier
  // (`alpine-linux` -> `alpineLinux`), so never emit ES shorthand here.
  const record = icons
    .map(({ slug, identifier }) => {
      const key = /^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(slug)
        ? slug
        : JSON.stringify(slug);
      return `  ${key}: ${identifier},`;
    })
    .join("\n");

  return `// @generated by scripts/sync-brand-icons.mjs from simple-icons@${version}.
// Do not edit manually; run \`npm run icons:brand:generate\`.
//
// Marks are vendored from simple-icons (CC0-1.0) so that \`simple-icons\` stays a
// devDependency and never reaches the bundler. Add or remove slugs in
// brandIconSlugs.ts, not here.

import type { LucideIcon } from "lucide-react";
import type { BrandIconSlug } from "./brandIconSlugs";
import { createBrandIcon } from "./createBrandIcon";

${declarations}

/**
 * Every vendored mark, keyed by its simple-icons slug.
 *
 * The \`Record<BrandIconSlug, LucideIcon>\` annotation makes \`npm run typecheck\`
 * fail if a slug in brandIconSlugs.ts has no generated mark, so the two files
 * cannot drift apart silently.
 */
export const GENERATED_BRAND_ICONS: Readonly<
  Record<BrandIconSlug, LucideIcon>
> = {
${record}
};
`;
}

export function generatedTextMatches(current, expected) {
  const normalize = (value) => value.replace(/\r\n?/gu, "\n");
  return normalize(current) === normalize(expected);
}

export async function formatGeneratedModule(source, filepath = GENERATED_PATH) {
  const config = await prettier.resolveConfig(filepath);
  return prettier.format(source, {
    ...(config ?? {}),
    filepath,
    parser: "typescript",
  });
}

function readSimpleIconsVersion() {
  const manifestPath = path.join(SIMPLE_ICONS_ROOT, "package.json");
  if (!fs.existsSync(manifestPath)) {
    fail("simple-icons is not installed; run `npm install` before generating");
  }
  const { version } = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
  if (typeof version !== "string" || version.length === 0) {
    fail("simple-icons package.json has no version");
  }
  return version;
}

export async function buildGeneratedModule() {
  const slugs = parseBrandIconSlugs(fs.readFileSync(SLUGS_PATH, "utf8"));
  const icons = collectBrandIcons(slugs);
  const rendered = renderBrandIconModule(icons, readSimpleIconsVersion());
  return { icons, source: await formatGeneratedModule(rendered) };
}

function parseMode(argv) {
  if (argv.length !== 1 || !["--check", "--write"].includes(argv[0])) {
    fail("usage: node scripts/sync-brand-icons.mjs (--check|--write)");
  }
  return argv[0];
}

async function main(argv) {
  const mode = parseMode(argv);
  const { icons, source } = await buildGeneratedModule();
  const current = fs.existsSync(GENERATED_PATH)
    ? fs.readFileSync(GENERATED_PATH, "utf8")
    : "";
  const synchronized = generatedTextMatches(current, source);

  if (mode === "--check" && !synchronized) {
    fail(
      "generated brand icon module is stale; run npm run icons:brand:generate",
    );
  }
  if (mode === "--write" && !synchronized) {
    fs.writeFileSync(GENERATED_PATH, source, "utf8");
  }

  const bytes = icons.reduce((total, icon) => total + icon.path.length, 0);
  console.log(
    `Brand icon catalog synchronized: ${icons.length} vendored simple-icons marks, ${bytes} bytes of path data.`,
  );
}

const invokedPath = process.argv[1]
  ? pathToFileURL(path.resolve(process.argv[1])).href
  : "";
if (invokedPath === import.meta.url) {
  try {
    await main(process.argv.slice(2));
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
