#!/usr/bin/env node
// Generates the two files that join the per-application login steps to the
// engines, so neither is kept by hand:
//
//   src-tauri/crates/sorng-browser-host/src/native_login_catalog.json
//     the native engine's view of the application catalog: the TypeScript
//     catalog (src/utils/connection/httpApplicationProfiles.ts) plus the
//     login steps of src/data/loginSteps/<family>/<id>.json;
//   src/utils/connection/httpLoginStepsRegistry.ts
//     the static imports through which the TypeScript catalog reads those
//     steps files.
//
// Usage: node scripts/generate-native-login-catalog.mjs [--check]
// With --check nothing is written and a stale file exits 1.
//
// Every steps file is validated on every run. A file the catalog cannot use
// (wrong format, unknown application, or an application that already has a
// reviewed automatic login) fails the run: nothing is generated from a tree
// in that state.
//
// What is emitted depends on DECLARATIVE_LOGIN_SUPPORTED
// (src/utils/connection/declarativeLoginSupport.ts). While it is off, steps
// files are validated and nothing of them is written: the registry stays
// empty and the native catalog keeps its five fields per profile, so adding
// or changing a steps file leaves both generated files untouched. Turning the
// flag on and running this script once is what puts the steps in both.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";
import * as prettier from "prettier";

const repo = fileURLToPath(new URL("..", import.meta.url));

export const NATIVE_LOGIN_CATALOG_PATH =
  "src-tauri/crates/sorng-browser-host/src/native_login_catalog.json";
export const LOGIN_STEPS_REGISTRY_PATH =
  "src/utils/connection/httpLoginStepsRegistry.ts";
const STEPS_DIRECTORY = "src/data/loginSteps";
const CATALOG_MODULE = "src/utils/connection/httpApplicationProfiles.ts";
const SUPPORT_MODULE = "src/utils/connection/declarativeLoginSupport.ts";
const USAGE = "Usage: node scripts/generate-native-login-catalog.mjs [--check]";

const posix = (value) => value.split(path.sep).join("/");

/** Every `<family>/<id>.json` under the steps directory, ordered by id. */
function listStepsFiles(stepsDirectory) {
  const files = [];
  const problems = [];
  if (!existsSync(stepsDirectory)) return files;
  for (const entry of readdirSync(stepsDirectory, { withFileTypes: true })) {
    if (!entry.isDirectory()) {
      if (entry.name.endsWith(".json"))
        problems.push(
          `${entry.name}: steps files live in ${STEPS_DIRECTORY}/<family>/<id>.json`,
        );
      continue;
    }
    const family = path.join(stepsDirectory, entry.name);
    for (const name of readdirSync(family)) {
      if (!name.endsWith(".json")) continue;
      files.push({
        id: name.slice(0, -".json".length),
        relative: `${entry.name}/${name}`,
        absolute: path.join(family, name),
      });
    }
  }
  const byId = new Map();
  for (const file of files)
    byId.set(file.id, [...(byId.get(file.id) ?? []), file.relative]);
  for (const [id, relatives] of byId)
    if (relatives.length > 1)
      problems.push(
        `${id} has more than one steps file: ${relatives.sort().join(", ")}`,
      );
  for (const file of files) {
    try {
      JSON.parse(readFileSync(file.absolute, "utf8"));
    } catch {
      problems.push(`${file.relative}: not valid JSON`);
    }
  }
  if (problems.length) throw new Error(problems.join("\n"));
  return files.sort((left, right) =>
    left.id < right.id ? -1 : left.id > right.id ? 1 : 0,
  );
}

/** `aws-console` -> `stepsAwsConsole`. */
const importName = (id) =>
  `steps${id
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("")}`;

/** The registry source for these files, as imports relative to `directory`. */
function renderLoginStepsRegistry(files, directory) {
  const names = new Map();
  for (const file of files) {
    const name = importName(file.id);
    if (names.has(name))
      throw new Error(
        `${file.id} and ${names.get(name)} would share one import name`,
      );
    names.set(name, file.id);
  }
  const specifier = (file) => {
    const relative = path.relative(directory, file.absolute);
    // Another drive has no relative path; an absolute one still resolves.
    if (path.isAbsolute(relative)) return posix(file.absolute);
    return relative.startsWith(".") ? posix(relative) : `./${posix(relative)}`;
  };
  return [
    "// Generated by scripts/generate-native-login-catalog.mjs from",
    `// ${STEPS_DIRECTORY}/<family>/<id>.json. Do not edit by hand:`,
    "// run `node scripts/generate-native-login-catalog.mjs`.",
    "// Empty while DECLARATIVE_LOGIN_SUPPORTED is off: the generator then",
    "// validates the steps files and ships none of them.",
    ...files.map(
      (file) => `import ${importName(file.id)} from "${specifier(file)}";`,
    ),
    "",
    "/** Every login steps file by application id, as written and not yet checked. */",
    "export const HTTP_LOGIN_STEPS_FILES: readonly (readonly [id: string, file: unknown])[] = [",
    ...files.map(
      (file) => `  [${JSON.stringify(file.id)}, ${importName(file.id)}],`,
    ),
    "];",
    "",
  ].join("\n");
}

/**
 * Evaluates the TypeScript catalog with `registrySource` in place of the
 * registry file, so the result reflects the steps directory as it is now and
 * not a registry that may be stale.
 */
async function loadCatalog(registrySource, registryDirectory) {
  const result = await build({
    stdin: {
      contents: [
        `export * from "./${CATALOG_MODULE}";`,
        `export { DECLARATIVE_LOGIN_SUPPORTED } from "./${SUPPORT_MODULE}";`,
      ].join("\n"),
      resolveDir: repo,
      loader: "ts",
    },
    bundle: true,
    platform: "node",
    format: "cjs",
    write: false,
    packages: "external",
    logLevel: "silent",
    plugins: [
      {
        name: "login-steps-registry",
        setup(bundle) {
          // esbuild filters are Go regular expressions: no flags.
          bundle.onLoad({ filter: /[\\/]httpLoginStepsRegistry\.ts$/ }, () => ({
            contents: registrySource,
            loader: "ts",
            resolveDir: registryDirectory,
          }));
        },
      },
    ],
  });
  const module = { exports: {} };
  new Function("require", "module", "exports", result.outputFiles[0].text)(
    createRequire(import.meta.url),
    module,
    module.exports,
  );
  return module.exports;
}

/**
 * The native catalog as data. An existing entry keeps exactly the five fields
 * the native engine reads today; a profile in `steps` also carries its
 * `declarativeLogin`. `capability` is never derived from steps: the native
 * authority uses it to decide what single-form login may do. `modeOf` is the
 * catalog's `getHttpLoginStepsMode`: `additive` for a profile that already
 * signs in by form detection (that login stays the fallback), `exclusive` for
 * one that did not. The support flag is announced only when on, so an absent
 * key means off.
 */
export function renderNativeLoginCatalog({
  profiles,
  joomla,
  steps,
  modeOf,
  declarativeLoginSupported,
}) {
  return JSON.parse(
    JSON.stringify({
      profiles: Object.fromEntries(
        profiles.map((profile) => {
          const file = steps.get(profile.id);
          return [
            profile.id,
            {
              capability: profile.capability,
              loginFlow: profile.loginFlow,
              emailOnly: profile.emailOnly,
              selectors: profile.selectors,
              sameOriginLoginFrames: profile.sameOriginLoginFrames,
              declarativeLogin: file && {
                mode: modeOf(profile),
                credentialOrigins: file.credentialOrigins,
                passwordOnly: file.passwordOnly,
                loginSteps: file.loginSteps,
              },
            },
          ];
        }),
      ),
      joomla,
      ...(declarativeLoginSupported ? { declarativeLoginSupported: true } : {}),
    }),
  );
}

/** Formats like the committed file, wherever the output is written. */
async function format(source, committedPath) {
  const filepath = path.join(repo, committedPath);
  return prettier.format(source, {
    ...(await prettier.resolveConfig(filepath)),
    filepath,
  });
}

const sameText = (file, expected) =>
  existsSync(file) &&
  readFileSync(file, "utf8").replaceAll("\r\n", "\n") === expected;

/**
 * Generates both files, or with `check` reports which of them are stale. The
 * three paths default to the repository's own; tests pass scratch paths.
 * `declarativeLoginSupported` defaults to the catalog's own flag; passing it
 * is for tests and for engine fixtures that need the steps before switch-on.
 */
export async function generateNativeLoginCatalog({
  check = false,
  stepsDirectory = path.join(repo, STEPS_DIRECTORY),
  catalogPath = path.join(repo, NATIVE_LOGIN_CATALOG_PATH),
  registryPath = path.join(repo, LOGIN_STEPS_REGISTRY_PATH),
  declarativeLoginSupported,
} = {}) {
  const files = listStepsFiles(stepsDirectory);
  const registryDirectory = path.dirname(registryPath);
  // Validation always sees every steps file, whatever is emitted below.
  const catalog = await loadCatalog(
    renderLoginStepsRegistry(files, registryDirectory),
    registryDirectory,
  );

  const problems = catalog.HTTP_APPLICATION_LOGIN_STEPS_PROBLEMS;
  if (problems.length)
    throw new Error(
      problems
        .map(
          ({ id, problem }) =>
            `${files.find((file) => file.id === id)?.relative ?? id}: ${problem}`,
        )
        .join("\n"),
    );

  // Off: validated above, emitted nowhere. No engine can act on steps that
  // are in neither generated file.
  const supported =
    declarativeLoginSupported ?? catalog.DECLARATIVE_LOGIN_SUPPORTED;
  const emitted = supported ? files : [];
  const native = renderNativeLoginCatalog({
    profiles: catalog.HTTP_APPLICATION_PROFILES,
    joomla: Object.fromEntries(
      catalog.JOOMLA_VERSION_OPTIONS.map(({ value }) => [
        value,
        catalog.getJoomlaLoginSelectors(value),
      ]),
    ),
    steps: supported ? catalog.HTTP_APPLICATION_LOGIN_STEPS : new Map(),
    modeOf: catalog.getHttpLoginStepsMode,
    declarativeLoginSupported: supported,
  });
  const outputs = [
    [
      catalogPath,
      await format(JSON.stringify(native, null, 2), NATIVE_LOGIN_CATALOG_PATH),
    ],
    [
      registryPath,
      await format(
        renderLoginStepsRegistry(emitted, registryDirectory),
        LOGIN_STEPS_REGISTRY_PATH,
      ),
    ],
  ];
  const stale = outputs
    .filter(([file, text]) => !sameText(file, text))
    .map(([file]) => file);
  if (!check) for (const [file, text] of outputs) writeFileSync(file, text);
  return {
    stale: check ? stale : [],
    profiles: catalog.HTTP_APPLICATION_PROFILES.length,
    steps: files.length,
    emitted: emitted.length,
  };
}

async function main(args) {
  if (args.some((arg) => arg !== "--check") || args.length > 1)
    throw new Error(USAGE);
  const check = args.includes("--check");
  const result = await generateNativeLoginCatalog({ check });
  if (result.stale.length)
    throw new Error(
      [
        ...result.stale.map(
          (file) => `${posix(path.relative(repo, file))} is stale`,
        ),
        "Run: node scripts/generate-native-login-catalog.mjs",
      ].join("\n"),
    );
  console.log(
    `${check ? "Checked" : "Generated"} the native login catalog: ${result.profiles} profiles; ${result.steps} login steps files validated, ${result.emitted} emitted${
      result.emitted < result.steps ? " (declarative login is off)" : ""
    }`,
  );
}

const invokedPath = process.argv[1]
  ? pathToFileURL(path.resolve(process.argv[1])).href
  : "";
if (invokedPath === import.meta.url) {
  try {
    await main(process.argv.slice(2));
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
