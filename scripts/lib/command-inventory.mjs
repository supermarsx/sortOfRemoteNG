/** Canonical, feature-preserving input for bounded native command registrars. */
export const commandName = ({ path }) => path.split("::").at(-1);

export function sortCommands(commands) {
  return [...commands].sort((a, b) =>
    commandName(a) < commandName(b)
      ? -1
      : commandName(a) > commandName(b)
        ? 1
        : 0,
  );
}

export function renderCommandInventory(manifest) {
  if (manifest.version !== 1 || !Array.isArray(manifest.commands))
    throw new Error("Unsupported command inventory");
  if (manifest.commands.length === 0 || manifest.commands.length > 250)
    throw new Error(
      "A command registrar must contain between 1 and 250 commands",
    );
  const seen = new Set();
  for (const entry of manifest.commands) {
    if (!/^[a-z_]\w*(?:::[a-z_]\w*)+$/.test(entry.path ?? ""))
      throw new Error("Invalid command path");
    if (Object.keys(entry).some((key) => !["path", "cfg"].includes(key)))
      throw new Error("Unknown command field");
    if (entry.cfg !== undefined && !/^[\w\s=,"()-]+$/.test(entry.cfg))
      throw new Error("Invalid command feature gate");
    const name = commandName(entry);
    if (seen.has(name)) throw new Error(`Duplicate command: ${name}`);
    seen.add(name);
  }
  const commands = sortCommands(manifest.commands);
  const line = (entry, value) =>
    `${entry.cfg ? `    #[cfg(${entry.cfg})]\n` : ""}    ${value},`;
  return `// @generated by scripts/generate-command-inventory.mjs; edit commands.json instead.
use crate::*;

pub const COMMAND_NAMES: &[&str] = &[
${commands.map((entry) => line(entry, JSON.stringify(commandName(entry)))).join("\n")}
];

pub fn is_command(command: &str) -> bool {
    COMMAND_NAMES.binary_search(&command).is_ok()
}

pub fn build() -> impl Fn(tauri::ipc::Invoke<tauri::Wry>) -> bool + Send + Sync + 'static {
    tauri::generate_handler![
${commands
  .map((entry) =>
    line(entry, entry.path)
      .split("\n")
      .map((part) => `    ${part}`)
      .join("\n"),
  )
  .join("\n")}
    ]
}

#[cfg(test)]
mod tests {
    #[test]
    fn inventory_is_sorted_unique_and_bounded() {
        let names = super::COMMAND_NAMES;
        assert!(names.len() <= 250);
        assert!(names.windows(2).all(|pair| pair[0] < pair[1]));
        assert!(names.iter().all(|name| super::is_command(name)));
        assert!(!super::is_command("__unknown_command__"));
    }
}
`;
}
